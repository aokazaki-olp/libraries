/**
 * 旧字体・異体字を通用字体（常用漢字ベース）に変換する
 * 1文字ずつマップ照合するため O(n) の1パス処理
 *
 * @param {string} name
 * @returns {string}
 */
function toCommonForm(name) {
  if (!name) return name ?? '';
  return [...name].map(ch => KANJI_MAP.get(ch) ?? ch).join('');
}

